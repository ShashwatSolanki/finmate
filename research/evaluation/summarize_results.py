"""Summarize per-case benchmark output and paired condition differences."""
from __future__ import annotations
import argparse, csv, json, random, statistics
from pathlib import Path

METRICS=["http_ok","route_correct","numeric_correct","memory_correct","abstention_correct","agentic_correct","invoice_artifacts_present","invoice_payload_correct","task_completed","retrieval_hit_at_5"]

def load(path): return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
def binval(v): return isinstance(v,bool) or (isinstance(v,(int,float)) and not isinstance(v,bool) and v in (0,1))
def values(rows,key): return [int(r[key]) for r in rows if binval(r.get(key))]
def ci(vals,n=10000,seed=20261010):
    if not vals:return None
    rng=random.Random(seed); size=len(vals); means=sorted(sum(vals[rng.randrange(size)] for _ in range(size))/size for _ in range(n))
    return [means[int(.025*n)],means[min(n-1,int(.975*n))]]
def rate(rows,key):
    vals=values(rows,key)
    return {"n":len(vals),"successes":sum(vals),"rate":sum(vals)/len(vals),"ci95_bootstrap":ci(vals)} if vals else None
def summarize(rows):
    out={"condition":rows[0].get("condition","unknown") if rows else "empty","cases":len(rows),"metrics":{}}
    for key in METRICS: out["metrics"][key]=rate(rows,key)
    lat=sorted(float(r["latency_seconds"]) for r in rows if isinstance(r.get("latency_seconds"),(int,float)))
    if lat:
        idx=max(0,min(len(lat)-1,int(.95*len(lat)+.999999)-1))
        out["latency_seconds"]={"n":len(lat),"mean":statistics.mean(lat),"median":statistics.median(lat),"p95_nearest_rank":lat[idx]}
    rr=[float(r["retrieval_reciprocal_rank"]) for r in rows if isinstance(r.get("retrieval_reciprocal_rank"),(int,float))]
    if rr: out["retrieval"]={"n":len(rr),"mrr":statistics.mean(rr),"hit_at_5":sum(float(r["retrieval_hit_at_5"])==1 for r in rows if isinstance(r.get("retrieval_hit_at_5"),(int,float)))/len(rr)}
    out["by_group"]={}
    for group in sorted(set(r.get("group","unknown") for r in rows)):
        g=[r for r in rows if r.get("group")==group]
        out["by_group"][group]={"cases":len(g),"task_completion":rate(g,"task_completed"),"numeric_accuracy":rate(g,"numeric_correct"),"memory_accuracy":rate(g,"memory_correct"),"route_accuracy":rate(g,"route_correct"),"agentic_accuracy":rate(g,"agentic_correct"),"abstention_accuracy":rate(g,"abstention_correct"),"invoice_payload_accuracy":rate(g,"invoice_payload_correct")}
    return out
def paired(a,b,key,n=10000,seed=20261011):
    ma={r["case_id"]:r.get(key) for r in a}; mb={r["case_id"]:r.get(key) for r in b}
    pairs=[(float(ma[k]),float(mb[k])) for k in sorted(set(ma)&set(mb)) if binval(ma[k]) and binval(mb[k])]
    if not pairs:return None
    diffs=[x-y for x,y in pairs]; rng=random.Random(seed); size=len(diffs)
    samples=sorted(sum(diffs[rng.randrange(size)] for _ in range(size))/size for _ in range(n))
    return {"n_paired":size,"mean_difference_a_minus_b":statistics.mean(diffs),"ci95_bootstrap":[samples[int(.025*n)],samples[min(n-1,int(.975*n))]]}
def main():
    ap=argparse.ArgumentParser(); ap.add_argument("results",nargs="+",type=Path); ap.add_argument("--compare",action="store_true"); ap.add_argument("--out-dir",type=Path,default=Path("research_results")); a=ap.parse_args()
    pairs=[(x.stem,load(x)) for x in a.results]; summaries=[summarize(r) for _,r in pairs]; result={"summaries":summaries}
    if a.compare and len(pairs)>1:
        baseline_name,baseline=pairs[0]; result["paired_comparisons"]={}
        for name,rows in pairs[1:]:
            result["paired_comparisons"][f"{name}_minus_{baseline_name}"]={m:paired(rows,baseline,m) for m in ["task_completed","numeric_correct","memory_correct","route_correct","agentic_correct","invoice_payload_correct"]}
    a.out_dir.mkdir(parents=True,exist_ok=True); (a.out_dir/"summary.json").write_text(json.dumps(result,indent=2),encoding="utf-8")
    lines=["# FinMate research evaluation summary","","Only treat these as experimental results if the input JSONL was generated by actual benchmark executions. These metrics do not establish population representativeness.",""]
    for s in summaries:
        lines.extend([f"## {s['condition']}",f"Cases: {s['cases']}","","| Metric | n | Correct / total | Rate | Bootstrap 95% CI |","|---|---:|---:|---:|---:|"])
        for k,v in s["metrics"].items():
            if v:
                lo,hi=v["ci95_bootstrap"]; lines.append(f"| {k} | {v['n']} | {v['successes']}/{v['n']} | {v['rate']:.3f} | [{lo:.3f}, {hi:.3f}] |")
        if s.get("latency_seconds"):
            x=s["latency_seconds"]; lines.append(f"\nLatency: median={x['median']:.3f}s, mean={x['mean']:.3f}s, p95={x['p95_nearest_rank']:.3f}s (n={x['n']}).")
        if s.get("retrieval"): lines.append(f"Retrieval: Hit@5={s['retrieval']['hit_at_5']:.3f}, MRR={s['retrieval']['mrr']:.3f} (n={s['retrieval']['n']}).")
        lines.append("")
    if result.get("paired_comparisons"):
        lines += ["## Paired differences","Differences are listed condition A minus the first file supplied (baseline). Positive values favour A for correctness metrics."]
        for name,metrics in result["paired_comparisons"].items():
            lines.append(f"\n### {name}")
            for key,x in metrics.items():
                if x: lines.append(f"- {key}: {x['mean_difference_a_minus_b']:.3f}; 95% bootstrap CI [{x['ci95_bootstrap'][0]:.3f}, {x['ci95_bootstrap'][1]:.3f}], n={x['n_paired']}")
    (a.out_dir/"summary.md").write_text("\n".join(lines),encoding="utf-8")
    with (a.out_dir/"claims_annotation_template.csv").open("w",encoding="utf-8",newline="") as fp:
        w=csv.writer(fp); w.writerow(["condition","case_id","reply","claim_id","claim_text","evidence_source","supported_yes_no","reviewer_id","notes"])
        for name,rows in pairs:
            for r in rows: w.writerow([r.get("condition",name),r.get("case_id",""),r.get("reply",""),"","","","","",""])
    print(f"Wrote {a.out_dir/'summary.md'} and {a.out_dir/'summary.json'}")
if __name__=="__main__": main()
